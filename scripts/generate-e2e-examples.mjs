// 生成 e2e 示例清单：从 examples/ 全量递归扫描 *.html（排除 gallery index），
// 构建多级目录树（目录=功能层级，叶子=html 文件名，不含目录），输出为 TS 对象到
// tests/e2e/examples-e2e.ts。每个层级带 name（便于理解）。
// 完整 url = /examples/<顶级分类>/<子层级...>/<叶子 html 文件名>（由多级路径组合）。
// 用户后续手工裁剪为「每类一个测试 url」（事项1.3）。
import { readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const EXAMPLES = 'examples';
const OUT = 'tests/e2e/examples-e2e.ts';
const SKIP = new Set(['index.html', 'indexClaude.html']);

// 顶级分类中文名（已知 10 类）；其余按 key 人文化
const CATEGORY_NAMES = {
    animations: '动画',
    atmosphere: '大气',
    base: '基础',
    BOL: 'BOL',
    model: '模型',
    performance: '性能',
    physics: '物理',
    shaderToy: 'ShaderToy',
    system: '系统',
    other: '其他',
};

// 把目录名 / 文件名人文化：box_position_cubeSpline -> Box Position Cube Spline
function humanize(key) {
    return key
        .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
        .replace(/[-_]+/g, ' ')
        .trim()
        .split(/\s+/)
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(' ');
}

// 节点：{ name, children? } 目录；{ name, file } 叶子
const root = {};

function ensureDir(parent, key, name) {
    if (!parent[key]) parent[key] = { name, children: {} };
    return parent[key];
}

function walk(dir, parent) {
    for (const entry of readdirSync(dir)) {
        const full = join(dir, entry);
        const st = statSync(full);
        if (st.isDirectory()) {
            const node = ensureDir(parent, entry, humanize(entry));
            walk(full, node.children);
        } else if (entry.endsWith('.html') && !SKIP.has(entry)) {
            parent[entry] = { name: humanize(entry.replace(/\.html$/, '')), file: entry };
        }
    }
}

for (const cat of readdirSync(EXAMPLES)) {
    const catPath = join(EXAMPLES, cat);
    if (!statSync(catPath).isDirectory()) continue;
    const node = ensureDir(root, cat, CATEGORY_NAMES[cat] || humanize(cat));
    walk(catPath, node.children);
}

// 序列化为 TS（JSON 是合法 TS 字面量）
function serialize(node, indent) {
    const pad = '  '.repeat(indent);
    const pad1 = '  '.repeat(indent + 1);
    if (node.file) {
        return `${pad}{ name: ${JSON.stringify(node.name)}, file: ${JSON.stringify(node.file)} }`;
    }
    const keys = Object.keys(node.children);
    if (keys.length === 0) {
        return `${pad}{ name: ${JSON.stringify(node.name)}, children: {} }`;
    }
    const body = keys
        .map((k) => `${pad1}${JSON.stringify(k)}: ${serialize(node.children[k], indent + 1)}`)
        .join(',\n');
    return `${pad}{\n${pad1}name: ${JSON.stringify(node.name)},\n${pad1}children: {\n${body}\n${pad1}}\n${pad}}`;
}

